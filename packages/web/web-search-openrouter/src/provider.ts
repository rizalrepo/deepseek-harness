/** OpenRouter Responses API transport and response projection for web search. */
import { WebError } from '@deepseek-ai/dsh-web'
import type { WebSearchProvider, WebSearchRequest, WebSearchResult, WebSearchSource } from '@deepseek-ai/dsh-web'
import { z } from 'zod'

/** Search registry id. */
export const OPENROUTER_SEARCH_PROVIDER_ID = 'openrouter-web-search'

/** OpenRouter Responses API endpoint. */
export const OPENROUTER_RESPONSES_URL = 'https://openrouter.ai/api/v1/responses'

/** Default auxiliary search model; OpenRouter chooses a model for each request. */
export const OPENROUTER_DEFAULT_MODEL = 'openrouter/auto'

/** Highest server-side source count requested for one search. */
export const OPENROUTER_DEFAULT_MAX_RESULTS = 10

/** Maximum generated answer tokens for one auxiliary search. */
export const OPENROUTER_DEFAULT_MAX_OUTPUT_TOKENS = 2048

/** Settings and per-search credential callbacks snapshotted for an operation. */
export interface OpenRouterSearchOptions {
  /** OpenRouter model ID. */
  readonly model: string
  /** Maximum total search results returned by the server tool. */
  readonly maxResults: number
  /** Maximum answer tokens generated by Responses. */
  readonly maxOutputTokens: number
  /** Whether a credential source is configured, without reading its value. */
  readonly credentialAvailable: () => boolean
  /** Resolve and validate the API key for this operation. */
  readonly resolveApiKey: () => Promise<string>
  /** Check whether the configured credential is available for the selected route. */
  readonly ready: () => Promise<boolean>
}

/** Make one Responses API request with a bounded OpenRouter web-search server tool. */
export class OpenRouterSearchProvider implements WebSearchProvider {
  readonly id = OPENROUTER_SEARCH_PROVIDER_ID
  readonly description: NonNullable<WebSearchProvider['description']> = {
    en: 'Beta OpenRouter web search. Model inference and search may incur separate OpenRouter charges.',
    zh: 'OpenRouter 网页搜索仍处于 Beta 阶段。模型推理与搜索可能分别产生 OpenRouter 费用。',
  }

  constructor(private readonly resolveOptions: () => OpenRouterSearchOptions) {}

  available(): boolean {
    const options = this.resolveOptions()
    return options.model.trim().length > 0
      && isPositiveInteger(options.maxResults)
      && isPositiveInteger(options.maxOutputTokens)
      && options.credentialAvailable()
  }

  async ready(_llmProvider: string | undefined): Promise<boolean> {
    try {
      return await this.resolveOptions().ready()
    } catch {
      return false
    }
  }

  async search(request: WebSearchRequest, signal?: AbortSignal): Promise<WebSearchResult> {
    const options = this.resolveOptions()
    const apiKey = await resolveCredential(options.resolveApiKey, signal)
    throwIfAborted(signal)
    const maxResults = Math.min(options.maxResults, request.maxResults ?? options.maxResults)
    let response: Response
    try {
      response = await fetch(OPENROUTER_RESPONSES_URL, {
        method: 'POST',
        redirect: 'error',
        headers: {
          authorization: `Bearer ${apiKey}`,
          'content-type': 'application/json',
          accept: 'application/json',
        },
        body: JSON.stringify({
          model: options.model,
          input: [{
            type: 'message',
            role: 'user',
            content: [{ type: 'input_text', text: request.query }],
          }],
          tools: [{
            type: 'openrouter:web_search',
            parameters: { max_uses: 1, max_total_results: maxResults },
          }],
          tool_choice: 'required',
          max_output_tokens: options.maxOutputTokens,
        }),
        ...signal === undefined ? {} : { signal },
      })
    } catch (error: unknown) {
      if (signal?.aborted === true || isAbortError(error)) throw aborted(signal, error)
      throw endpointError(`OpenRouter request failed: ${String(error)}`, error)
    }

    if (!response.ok) {
      let detail = ''
      try {
        const payload: unknown = await response.json()
        const error = responseError.safeParse(payload)
        if (error.success) detail = `: ${error.data.error.message}`
      } catch (error: unknown) {
        if (signal?.aborted === true || isAbortError(error)) throw aborted(signal, error)
      }
      if (signal?.aborted === true) throw aborted(signal)
      throw endpointError(`OpenRouter API error (HTTP ${response.status})${detail}`)
    }

    try {
      const payload: unknown = await response.json()
      return mapResponsesResult(payload)
    } catch (error: unknown) {
      if (signal?.aborted === true || isAbortError(error)) throw aborted(signal, error)
      if (error instanceof WebError) throw endpointError(error.message, error)
      throw endpointError(`OpenRouter returned an invalid response body: ${String(error)}`, error)
    }
  }
}

/** Schemas validate untrusted Responses JSON once at the HTTP boundary. */
const responsePayload = z.object({
  status: z.literal('completed'),
  output: z.array(z.object({ type: z.string() }).passthrough()),
})
const responseMessage = z.object({ role: z.string(), content: z.array(z.object({ type: z.string() }).passthrough()) })
const responseError = z.object({ error: z.object({ message: z.string() }).passthrough() }).passthrough()
const outputText = z.object({
  text: z.string(),
  annotations: z.array(z.object({ type: z.string() }).passthrough()).optional(),
})
const urlCitation = z.object({ type: z.literal('url_citation'), url: z.string().url(), title: z.string().optional() })

type ParsedResponsePayload = z.infer<typeof responsePayload>
type ParsedMessage = z.infer<typeof responseMessage>
type ParsedOutputText = z.infer<typeof outputText>
type ParsedCitation = z.infer<typeof urlCitation>

/** Validate the Responses result and map assistant text plus URL citation annotations. */
export function mapResponsesResult(value: unknown): WebSearchResult {
  let payload: ParsedResponsePayload
  try { payload = responsePayload.parse(value) }
  catch { throw invalidResponse() }

  let completedSearch = false
  const content: string[] = []
  const sources: WebSearchSource[] = []
  const seen = new Set<string>()

  for (const item of payload.output) {
    if (item.type === 'web_search_call') {
      if (item.status !== 'completed') throw invalidResponse()
      completedSearch = true
      continue
    }
    if (item.type !== 'message') continue
    let message: ParsedMessage
    try { message = responseMessage.parse(item) }
    catch { throw invalidResponse() }
    if (message.role !== 'assistant') continue
    for (const part of message.content) {
      if (part.type !== 'output_text') continue
      let text: ParsedOutputText
      try { text = outputText.parse(part) }
      catch { throw invalidResponse() }
      const piece = text.text.trim()
      if (piece.length > 0) content.push(piece)
      for (const candidate of text.annotations ?? []) {
        if (candidate.type !== 'url_citation') continue
        let citation: ParsedCitation
        try { citation = urlCitation.parse(candidate) }
        catch { throw invalidResponse() }
        if (!isHttpUrl(citation.url) || seen.has(citation.url)) continue
        seen.add(citation.url)
        sources.push({
          url: citation.url,
          ...citation.title !== undefined && citation.title.length > 0 ? { title: citation.title } : {},
        })
      }
    }
  }

  if (!completedSearch) throw invalidResponse()
  const answer = content.join('\n\n').trim()
  return { ...(answer.length > 0 ? { content: answer } : {}), sources, truncated: false }
}

/** Run credential resolution under cancellation and translate failures to WebError. */
async function resolveCredential(resolve: () => Promise<string>, signal?: AbortSignal): Promise<string> {
  throwIfAborted(signal)
  try {
    const key = await abortable(resolve(), signal)
    if (key.length === 0) throw new Error('credential is empty')
    return key
  } catch (error: unknown) {
    if (signal?.aborted === true || isAbortError(error)) throw aborted(signal, error)
    if (error instanceof WebError) throw error
    throw new WebError(`OpenRouter API key resolution failed: ${String(error)}`, 'WEB_PROVIDER_ERROR', { cause: error })
  }
}

/** Race a credential read against cancellation while observing late settlement. */
function abortable<T>(operation: Promise<T>, signal?: AbortSignal): Promise<T> {
  if (signal === undefined) return operation
  if (signal.aborted) return Promise.reject(aborted(signal))
  const { promise, resolve, reject } = Promise.withResolvers<T>()
  const onAbort = (): void => reject(aborted(signal))
  signal.addEventListener('abort', onAbort, { once: true })
  void operation.then(
    (value) => { signal.removeEventListener('abort', onAbort); resolve(value) },
    (error) => { signal.removeEventListener('abort', onAbort); reject(error) },
  )
  return promise
}

/** Throw the stable cancellation error before starting another operation. */
function throwIfAborted(signal?: AbortSignal): void {
  if (signal?.aborted === true) throw aborted(signal)
}

/** Build the provider cancellation error. */
function aborted(signal?: AbortSignal, fallback?: unknown): WebError {
  return new WebError('OpenRouter web search aborted', 'WEB_ABORTED', {
    cause: signal?.aborted === true ? signal.reason : fallback,
  })
}

/** Add the configured endpoint and its configuration boundary to transport failures. */
function endpointError(message: string, cause?: unknown): WebError {
  return new WebError(
    `${message}\n\nThe OpenRouter web search request used ${OPENROUTER_RESPONSES_URL}. Configure the OpenRouter API key and model in the web-search-openrouter plugin; this does not change the conversation model provider.`,
    'WEB_PROVIDER_ERROR',
    cause === undefined ? undefined : { cause },
  )
}

/** Report malformed or incomplete Responses data without echoing untrusted payloads. */
function invalidResponse(): WebError {
  return new WebError('OpenRouter returned an invalid or incomplete web-search response', 'WEB_PROVIDER_ERROR')
}
/** Accept only absolute HTTP(S) citation URLs. */
function isHttpUrl(value: string): boolean {
  try {
    const url = new URL(value)
    return url.protocol === 'http:' || url.protocol === 'https:'
  } catch {
    return false
  }
}

/** True for a positive integer request bound. */
function isPositiveInteger(value: number): boolean {
  return Number.isInteger(value) && value > 0
}

/** True when Fetch or AbortSignal identifies cancellation. */
function isAbortError(error: unknown): boolean {
  return error instanceof DOMException && error.name === 'AbortError'
}
